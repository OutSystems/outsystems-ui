#!/usr/bin/env node
// @ts-check
/**
 * Renders `results/dashboard.json`, the data set behind the dashboard: the history of every suite's
 * index, one block per suite (its evals with next steps, its heatmap columns, the first and latest run
 * that carried it, extra data a metric contributes) and one cell per component × heatmap eval with a
 * concrete hint. The rows are the universe (lib/universe.mjs): every composable OML block with the cells of
 * the pattern or stylesheet it drives and its own block evals, then the platform styles. Every metric
 * describes its own cells through its `present` block (see suites.mjs), so this file knows no eval by id. Regenerated by every full `npm run evals` and by
 * `npm run evals:dashboard`; a test asserts the committed file is fresh.
 *
 *   node evals/tools/dashboard-data.mjs
 *
 * The dashboard reads this document from the artifact database; the file is the source to publish.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { createContext } from '../lib/context.mjs';
import { KIND_TEXT, KINDS, kindText, rowApplies } from '../lib/kinds.mjs';
import { insideDir } from '../lib/paths.mjs';
import { registry } from '../lib/registry.mjs';
import { normalizeHistoryEntry, normalizeRun } from '../lib/results.mjs';
import { buildUniverse, CATEGORY_LABEL } from '../lib/universe.mjs';
import { metricById, SUITES } from '../suites.mjs';

export const DASHBOARD_FILE = 'results/dashboard.json';

/** @typedef {{ s: number|null, w: 'ok'|'na'|'unmeasured', h: string }} Cell */

/** @param {string} id */
const presentOf = (id) => metricById(id)?.metric.present ?? null;

/**
 * Cell for a row the eval has no entry for: not applicable (the eval does not measure this kind of row, or
 * the metric said so for this row) or not measured (with the metric's reason).
 * @param {string} id
 * @param {{ kind?: string, category?: string, reason?: string, notApplicable?: { reason: string, hint?: string } }} ctx
 * @returns {Cell}
 */
function missingCell(id, ctx) {
	const present = presentOf(id);
	if (ctx.notApplicable) {
		const hint = ctx.notApplicable.hint ? ` ${ctx.notApplicable.hint}` : '';
		return { s: null, w: 'na', h: `Not applicable: ${ctx.notApplicable.reason}.${hint}` };
	}
	const kind = ctx.kind && KINDS.includes(/** @type {any} */ (ctx.kind)) ? ctx.kind : null;
	if (present && kind && !rowApplies(present, { kind, category: ctx.category ?? 'platform' })) {
		const measures = (present.appliesTo ?? []).map(measuresText).join(', ');
		return { s: null, w: 'na', h: `Not applicable: this eval measures ${measures}; ${kindText(kind)}.` };
	}
	// the metric named this row with a reason: its hint applies; a row it never mentioned gets a neutral text
	if (ctx.reason === undefined)
		return { s: null, w: 'unmeasured', h: 'Not measured: the eval reports no entry for this row.' };
	const fix = present?.unmeasuredHint ? ` ${present.unmeasuredHint}` : '';
	return { s: null, w: 'unmeasured', h: `Not measured (${ctx.reason}).${fix}` };
}

/** `block` → `OML blocks`, else the plural of the kind. @param {string} kind */
const measuresText = (kind) => (kind === 'block' ? 'OML blocks' : `${kind}s`);

/**
 * One heatmap cell: `s` score (or null), `w` why (`ok` | `na` | `unmeasured`), `h` hint text.
 * @param {string} id eval id
 * @param {any} row the metric's per-component row, or null when it has none for this row
 * @param {{ kind?: string, category?: string, reason?: string, notApplicable?: { reason: string, hint?: string } }} [ctx]
 * @returns {Cell}
 */
export function cellFor(id, row, ctx = {}) {
	if (!row) return missingCell(id, ctx);
	const present = presentOf(id);
	if (present?.cell) {
		const c = present.cell(row);
		return { s: c.s, w: 'ok', h: c.h };
	}
	return { s: typeof row.score === 'number' ? row.score : null, w: 'ok', h: '' };
}

/** `checkbox (src/scss/…/_checkbox.scss)` → `checkbox`. @param {string} name */
const baseName = (name) => name.replace(/ \(.*\)$/, '');

/**
 * The cells of one row of the universe: for every heatmap eval, the eval's entry for the row id (a block the
 * eval measures itself), else for the row's pattern, else for its stylesheet; unmeasured and not-applicable
 * entries are matched the same way. An eval that does not apply to the row and said nothing about it has no
 * cell: the page composes "not applicable" from the eval's appliesTo, which keeps the data set small.
 * @param {any[]} results metric results of the latest run
 * @param {import('../lib/universe.mjs').Row} row
 * @returns {Record<string, Cell>}
 */
export function componentCells(results, row) {
	/** @type {Record<string, Cell>} */
	const cells = {};
	const names = [row.id, row.runtime.pattern, row.runtime.style].filter((n) => n !== null);
	const mine = (/** @type {{ name: string }} */ u) => names.some((n) => u.name === n || u.name.startsWith(`${n} (`));
	for (const m of results) {
		const present = presentOf(m.id);
		if (!present?.heatmap) continue;
		const entries = /** @type {any[]} */ (Object.values(m.perComponent ?? {}));
		const hit = names.map((n) => entries.find((r) => r.name === n)).find(Boolean) ?? null;
		const na = (m.notApplicable ?? []).find(mine);
		const un = (m.unmeasured ?? []).find(mine);
		if (!hit && !na && !un && !rowApplies(present, row)) continue;
		cells[m.id] = cellFor(m.id, hit, {
			kind: row.kind,
			category: row.category,
			reason: un?.reason,
			notApplicable: na,
		});
	}
	return cells;
}

/**
 * The dashboard view of one metric result.
 * @param {any} m metric result of the latest run
 * @param {Record<string, number>} baseScores scores of the first run that carried the suite
 */
function evalOf(m, baseScores) {
	const present = presentOf(m.id);
	return {
		id: m.id,
		name: m.name,
		criterion: m.criterion,
		formula: m.formula,
		movable: m.movable,
		cls: m.cls ?? (m.movable ? 'movable' : 'structural'),
		score: m.score,
		base: baseScores[m.id] ?? null,
		summary: m.summary,
		appliesTo: present?.appliesTo ?? [...KINDS],
		scope: present?.scope ?? '',
		advice: present?.advice ? present.advice(m) : [m.summary],
		unmeasured: {
			n: (m.unmeasured ?? []).length,
			items: (m.unmeasured ?? []).map((/** @type {any} */ u) => ({ n: baseName(u.name), r: u.reason })),
		},
		notApplicable: (m.notApplicable ?? []).length,
		unmeasuredHint: present?.unmeasuredHint ?? '',
	};
}

/**
 * The block of one suite: present when the latest run carries it.
 * @param {import('../suites.mjs').Suite} suite
 * @param {import('../lib/results.mjs').HistoryEntry[]} history sorted by date
 * @param {any} latest the latest run, in the suites shape
 */
function suiteBlock(suite, history, latest) {
	const first = history.find((h) => h.suites[suite.id]);
	const latestSuite = latest.suites[suite.id];
	if (!first || !latestSuite) return null;
	// the category series start at the first run that carries them (the backfill gives every run its own)
	const firstCategories = history.find((h) => h.suites[suite.id]?.categories);
	const categories = latestSuite.categories
		? Object.fromEntries(
				Object.entries(latestSuite.categories).map(([category, c]) => [
					category,
					{
						index: /** @type {any} */ (c).index,
						evals: Object.keys(/** @type {any} */ (c).scores).length,
						base: firstCategories?.suites[suite.id].categories?.[category]?.index ?? null,
						baseLabel: firstCategories?.label ?? null,
					},
				])
			)
		: null;
	const results = /** @type {any[]} */ (latestSuite.results ?? []);
	/** @type {Record<string, unknown>} */
	let extra = {};
	for (const m of results) {
		const present = presentOf(m.id);
		if (present?.extra) extra = { ...extra, ...present.extra(m) };
	}
	return {
		id: suite.id,
		name: suite.name,
		indexName: suite.indexName,
		describe: suite.describe,
		tone: suite.tone,
		evals: results.map((m) => evalOf(m, first.suites[suite.id].scores)),
		heatmapEvals: results.filter((m) => presentOf(m.id)?.heatmap).map((m) => m.id),
		baseline: { label: first.label, sha: first.sha, date: first.date, index: first.suites[suite.id].index },
		latest: { index: latestSuite.index },
		categories,
		extra,
	};
}

/**
 * @param {string} evalsDir the `evals/` directory (holds `results/`)
 * @param {Date} [now]
 * @param {string} [root] the repository root the universe is read from (snapshot, registry, inventory)
 */
export function buildDashboardData(evalsDir, now = new Date(), root = path.resolve(evalsDir, '..')) {
	const read = (/** @type {string} */ ...p) =>
		JSON.parse(fs.readFileSync(insideDir(evalsDir, 'results', ...p), 'utf8'));
	/** @type {import('../lib/results.mjs').HistoryEntry[]} */
	const history = read('history.json')
		.map((/** @type {any} */ e) => normalizeHistoryEntry(e))
		.sort((/** @type {any} */ a, /** @type {any} */ b) => a.date.localeCompare(b.date));
	const last = history[history.length - 1];
	// the results branch keeps only latest.json; a checkout keeps every labelled run
	const latestFile = fs.existsSync(insideDir(evalsDir, 'results', `${last.label}.json`))
		? `${last.label}.json`
		: 'latest.json';
	const latest = normalizeRun(read(latestFile));

	const suites = SUITES.map((s) => suiteBlock(s, history, latest)).filter((b) => b !== null);
	const allResults = Object.values(latest.suites).flatMap((/** @type {any} */ s) => s.results ?? []);
	const ctx = createContext(root);
	const universe = buildUniverse(ctx.modelSnapshots(), registry(), ctx.inventory);
	const components = universe.map((row) => ({
		n: row.name,
		id: row.id,
		k: row.kind,
		c: row.category,
		f: row.flow,
		rt: { p: row.runtime.pattern, s: row.runtime.style },
		cells: componentCells(allResults, row),
	}));

	return {
		v: 5,
		generated: now.toISOString(),
		latest: { label: last.label, sha: last.sha, date: last.date },
		history,
		suites,
		components,
		kindTexts: KIND_TEXT,
		categoryLabels: CATEGORY_LABEL,
	};
}

/**
 * @param {string} evalsDir
 */
export function writeDashboardData(evalsDir) {
	const file = insideDir(evalsDir, DASHBOARD_FILE);
	fs.writeFileSync(file, `${JSON.stringify(buildDashboardData(evalsDir))}\n`);
	return file;
}

function main() {
	const evalsDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
	const file = writeDashboardData(evalsDir);
	process.stdout.write(`wrote ${path.relative(process.cwd(), file)} (${fs.statSync(file).size} bytes)\n`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
