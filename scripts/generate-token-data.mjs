/**
 * Generate shape.js
 */
function generateShape(variables, utilities) {
    const rectangularShapes = [];
    const roundShapes = [];
    const softShapes = [];
    
    const sizeNames = {
        '2xs': 'Extra extra small',
        'xs': 'Extra small',
        'sm': 'Small',
        'md': 'Medium',
        'lg': 'Large',
        'xl': 'Extra large',
        '2xl': 'Extra extra large',
    };
    
    Object.entries(variables).forEach(([varName, data]) => {
        if (varName.match(/^token-rectangular-(2xs|xs|sm|md|lg|xl|2xl)$/)) {
            const size = varName.match(/rectangular-(.+)$/)[1];
            const value = resolveValue(data.value, variables);
            
            rectangularShapes.push({
                name: "Rectangular",
                name2: sizeNames[size] || size,
                token: tokenToDotNotation(varName),
                css_variable: data.css_variable,
                utility_class: utilities[varName] ? utilities[varName][0] : `.${varName}`,
                value: value,
                usage: "",
            });
        } else if (varName.match(/^token-round-(2xs|xs|sm|md|lg|xl|2xl)$/)) {
            const size = varName.match(/round-(.+)$/)[1];
            const value = resolveValue(data.value, variables);
            
            roundShapes.push({
                name: "Round",
                name2: sizeNames[size] || size,
                token: tokenToDotNotation(varName),
                css_variable: data.css_variable,
                utility_class: utilities[varName] ? utilities[varName][0] : `.${varName}`,
                value: value,
                usage: "",
            });
        } else if (varName.match(/^token-soft-(2xs|xs|sm|md|lg|xl|2xl)$/)) {
            const size = varName.match(/soft-(.+)$/)[1];
            const value = resolveValue(data.value, variables);
            
            softShapes.push({
                name: "Soft",
                name2: sizeNames[size] || size,
                token: tokenToDotNotation(varName),
                css_variable: data.css_variable,
                utility_class: utilities[varName] ? utilities[varName][0] : `.${varName}`,
                value: value,
                usage: "",
            });
        }
    });
    
    const shapes = [...rectangularShapes, ...roundShapes, ...softShapes];
    
    const content = `export const Shapes = ${JSON.stringify(shapes, null, 4)};
`;
    
    writeModule('shape.ts', content);
    console.log('✓ Generated shape.ts');
}

/**
 * Parse the properties of one SCSS map body into a plain object.
 */
function parseScssMapProps(mapContent) {
    const props = {};
    for (const propMatch of mapContent.matchAll(/([a-z-]+):\s*\$?([^,\n]+)/g)) {
        const [, propName, propValue] = propMatch;
        props[propName.trim()] = propValue.trim().replace(/,\s*$/, '');
    }
    return props;
}

/**
 * Resolve one part of a composite typography token (font-size / font-weight /
 * line-height) into its scale token and actual value.
 */
function typographyPart(props, propName, tokenGroup, variables) {
    const ref = props[propName];
    const token = ref ? ref.replace(new RegExp(`^\\$?token-${tokenGroup}-`), '') : '';
    const varName = `token-${tokenGroup}-${token}`;
    const value = variables[varName] ? resolveValue(variables[varName].value, variables) : '';
    return { token, value };
}

/**
 * Human-readable name for a typography variant (e.g. Heading 1 bold).
 */
function formatTypographyName(category, variantParts) {
    if (category === 'display') return `Display ${variantParts[0]} ${variantParts[1]}`;
    if (category === 'heading') return `Heading ${variantParts[0].toUpperCase().replace('H', '')} ${variantParts[1]}`;
    if (category === 'body' && variantParts[0] === 'action') return `Body action ${variantParts[1]}`;
    if (category === 'body') return `Body ${variantParts[0]} ${variantParts[1]}`;
    return '';
}

/**
 * Parse composite typography tokens (SCSS maps)
 * Matches patterns like: $token-display-lg-regular: ( font-size: $token-font-size-900, ... );
 */
function parseTypographyMaps(content, variables) {
    const typographyTokens = {
        display: [],
        heading: [],
        body: []
    };

    // Match SCSS maps for typography
    const mapRegex = /\$token-(display|heading|body)-([a-z0-9-]+):\s*\(([\s\S]*?)\);/g;

    let match;
    while ((match = mapRegex.exec(content)) !== null) {
        const [, category, variant, mapContent] = match;

        const props = parseScssMapProps(mapContent);
        const size = typographyPart(props, 'font-size', 'font-size', variables);
        const weight = typographyPart(props, 'font-weight', 'font-weight', variables);
        const lineHeight = typographyPart(props, 'line-height', 'font-line-height', variables);

        typographyTokens[category].push({
            token: `${category}.${variant.replace(/-/g, '.')}`,
            name: formatTypographyName(category, variant.split('-')),
            typeface: "Inter",
            size: {
                token: `scale.${size.token}`,
                value: size.value,
            },
            line_height: {
                token: `scale.${lineHeight.token}`,
                value: lineHeight.value,
            },
            weight: {
                token: `font-weight.${weight.token}`,
                value: weight.value,
            },
        });
    }

    return typographyTokens;
}

/**
 * Generate typography.js
 */
function generateTypography(variables, utilities, variablesContent) {
    // Parse composite typography tokens
    const typographyMaps = parseTypographyMaps(variablesContent, variables);
    
    // Sort Display tokens (lg before md/sm)
    const displayOrder = { 'lg': 0, 'md': 1, 'sm': 2 };
    typographyMaps.display.sort((a, b) => {
        const aSize = a.token.split('.')[1];
        const bSize = b.token.split('.')[1];
        return (displayOrder[aSize] || 99) - (displayOrder[bSize] || 99);
    });
    
    // Sort Heading tokens (h1 to h6, then by weight)
    const weightOrder = { 'bold': 0, 'semi-bold': 1, 'medium': 2, 'regular': 3 };
    typographyMaps.heading.sort((a, b) => {
        const aParts = a.token.split('.');
        const bParts = b.token.split('.');
        const aLevel = parseInt(aParts[1].replace('h', ''));
        const bLevel = parseInt(bParts[1].replace('h', ''));
        if (aLevel !== bLevel) return aLevel - bLevel;
        return (weightOrder[aParts[2]] || 99) - (weightOrder[bParts[2]] || 99);
    });
    
    // Sort Body tokens
    const sizeOrder = { 'action': 0, 'lg': 1, 'md': 2, 'sm': 3, 'xs': 4 };
    typographyMaps.body.sort((a, b) => {
        const aParts = a.token.split('.');
        const bParts = b.token.split('.');
        const aSize = aParts[1];
        const bSize = bParts[1];
        if (aSize !== bSize) return (sizeOrder[aSize] || 99) - (sizeOrder[bSize] || 99);
        return (weightOrder[aParts[2]] || 99) - (weightOrder[bParts[2]] || 99);
    });
    
    // Generate FontFamily
    const fontFamily = [{
        token: "font.family",
        css_variable: "--token-font-family",
        utility_class: ".token-font-family",
        value: "Inter, sans-serif",
    }];
    
    // Generate Weight tokens
    const weights = [];
    const weightNames = ['thin', 'extra-light', 'light', 'regular', 'medium', 'semi-bold', 'bold', 'extra-bold', 'black'];
    weightNames.forEach(name => {
        const varName = `token-font-weight-${name}`;
        if (variables[varName]) {
            weights.push({
                token: `font.weight.${name}`,
                css_variable: `--${varName}`,
                utility_class: `.${varName}`,
                value: resolveValue(variables[varName].value, variables),
            });
        }
    });
    
    // Generate Size tokens
    const sizes = [];
    Object.entries(variables).forEach(([varName, data]) => {
        if (varName.match(/^token-font-size-\d+$/)) {
            const scale = varName.replace('token-font-size-', '');
            sizes.push({
                token: `font.size.${scale}`,
                css_variable: data.css_variable,
                utility_class: `.${varName}`,
                value: resolveValue(data.value, variables),
            });
        }
    });
    // Sort sizes by scale number
    sizes.sort((a, b) => {
        const aNum = parseInt(a.token.split('.')[2]);
        const bNum = parseInt(b.token.split('.')[2]);
        return aNum - bNum;
    });
    
    // Generate LetterSpacing tokens
    const letterSpacings = [];
    Object.entries(variables).forEach(([varName, data]) => {
        if (varName.match(/^token-font-letter-spacing-\d+$/)) {
            const scale = varName.replace('token-font-letter-spacing-', '');
            letterSpacings.push({
                token: `font.letter.spacing.${scale}`,
                css_variable: data.css_variable,
                utility_class: `.${varName}`,
                value: resolveValue(data.value, variables),
            });
        }
    });
    letterSpacings.sort((a, b) => {
        const aNum = parseInt(a.token.split('.')[3]);
        const bNum = parseInt(b.token.split('.')[3]);
        return aNum - bNum;
    });
    
    // Generate LineHeight tokens
    const lineHeights = [];
    Object.entries(variables).forEach(([varName, data]) => {
        if (varName.match(/^token-font-line-height-(\d+|full)$/)) {
            const scale = varName.replace('token-font-line-height-', '');
            lineHeights.push({
                token: `font.line.height.${scale}`,
                css_variable: data.css_variable,
                utility_class: `.${varName}`,
                value: resolveValue(data.value, variables),
            });
        }
    });
    // Sort line heights (numbers first, then 'full')
    lineHeights.sort((a, b) => {
        const aScale = a.token.split('.')[3];
        const bScale = b.token.split('.')[3];
        if (aScale === 'full') return 1;
        if (bScale === 'full') return -1;
        return parseInt(aScale) - parseInt(bScale);
    });
    
    const content = `export const Display = ${JSON.stringify(typographyMaps.display, null, 4)};

export const Heading = ${JSON.stringify(typographyMaps.heading, null, 4)};

export const Body = ${JSON.stringify(typographyMaps.body, null, 4)};

export const FontFamily = ${JSON.stringify(fontFamily, null, 4)};

export const Weight = ${JSON.stringify(weights, null, 4)};

export const Size = ${JSON.stringify(sizes, null, 4)};

export const LetterSpacing = ${JSON.stringify(letterSpacings, null, 4)};

export const LineHeight = ${JSON.stringify(lineHeights, null, 4)};
`;
    
    writeModule('typography.ts', content);
    console.log('✓ Generated typography.ts');
}

