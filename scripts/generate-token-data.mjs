#!/usr/bin/env node

/**
 * Generates Storybook Foundations data from design-token SCSS.
 *
 * Reads:
 *   • src/scss/tokens/_variables.scss  (from npm run build:tokens)
 *
 * OUI builds with --utilities false, so utility classes are inferred as
 * `.token-*` by convention (no _utilities.scss parse).
 *
 * Writes:
 *   • stories/_helpers/token-data/*.ts — consumed by Foundations docs pages (Phase 2+)
 *
 * Run: npm run docs:tokens  (after npm run build:tokens)
 *
 * Adapted from OutSystems/runtime-mobile-widgets-js (.storybook/tokens/data/generate-tokens.js).
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const repoRoot = path.resolve(__dirname, '..');
const VARIABLES_FILE = path.join(repoRoot, 'src/scss/tokens/_variables.scss');
const OUTPUT_DIR = path.join(repoRoot, 'stories/_helpers/token-data');

const FILE_HEADER = [
	'// Generated by scripts/generate-token-data.mjs — do not edit by hand.',
	'// Regenerate: npm run docs:tokens (requires npm run build:tokens first)',
	'',
].join('\n');

function writeModule(filename, body) {
	fs.mkdirSync(OUTPUT_DIR, { recursive: true });
	fs.writeFileSync(path.join(OUTPUT_DIR, filename), FILE_HEADER + body);
}

/**
 * Parse SCSS variables file
 * Matches patterns like: $token-name: var(--token-name, value);
 */
function parseVariables(content) {
    const variables = {};
    // Match var() with proper handling of nested parentheses (like cubic-bezier)
    const lines = content.split('\n');
    
    for (const line of lines) {
        const match = line.match(/\$([a-zA-Z0-9_-]+):\s*var\(--([a-zA-Z0-9_-]+),\s*(.+?)\);/);
        if (match) {
            const [, varName, cssVar, value] = match;
            variables[varName] = {
                scss_variable: `$${varName}`,
                css_variable: `--${cssVar}`,
                value: value.trim().replace(/^\$/, ''), // Remove leading $ from references
            };
        }
    }
    
    return variables;
}

/**
 * Parse utility classes from SCSS
 * Matches patterns like: .class-name { property: $variable; }
 */
function parseUtilityClasses(content) {
    const utilities = {};
    const regex = /\.([a-zA-Z0-9_-]+)\s*\{[^}]*(?:border|color|background|box-shadow|z-index|font|line-height|letter-spacing|margin|padding):\s*\$([a-zA-Z0-9_-]+)/g;
    
    let match;
    while ((match = regex.exec(content)) !== null) {
        const [, className, varName] = match;
        if (!utilities[varName]) {
            utilities[varName] = [];
        }
        utilities[varName].push(`.${className}`);
    }
    
    return utilities;
}

/**
 * Resolve variable references to get actual values
 */
function resolveValue(value, variables, depth = 0) {
    // Prevent infinite recursion
    if (depth > 10) {
        return value;
    }
    
    // Trim whitespace
    value = value.trim();
    
    // If value references another variable (e.g., token-scale-100)
    // Check if it's a simple token reference (no spaces, special chars except hyphens)
    if (/^[a-zA-Z0-9_-]+$/.test(value)) {
        // Try to find this token in variables
        const refVarName = value.replace(/^\$/, '');
        if (variables[refVarName]) {
            return resolveValue(variables[refVarName].value, variables, depth + 1);
        }
    }
    
    return value;
}

/**
 * Resolve compound box-shadow fallbacks (multiple layers of token-shadow-* refs).
 */
function resolveShadowValue(value, variables, depth = 0) {
    if (depth > 10) {
        return value;
    }

    const layers = value.trim().split(/,\s*(?=\$?token-shadow-)/);

    return layers
        .map((layer) =>
            layer
                .trim()
                .split(/\s+/)
                .map((part) => {
                    const ref = part.replace(/^\$/, '');
                    if (variables[ref]) {
                        return resolveValue(variables[ref].value, variables, depth + 1);
                    }
                    return part;
                })
                .join(' ')
        )
        .join(', ');
}

/**
 * Convert token name to dot notation
 * Example: token-border-size-0 -> border.size.0
 */
function tokenToDotNotation(tokenName) {
    return tokenName
        .replace(/^token-/, '')
        .replace(/-/g, '.');
}

/**
 * Generate borders.js
 */
function generateBorders(variables, utilities) {
    const borderSizes = [];
    const borderStyles = [];
    const borderRadii = [];
    
    Object.entries(variables).forEach(([varName, data]) => {
        if (varName.startsWith('token-border-size-')) {
            const tokenName = tokenToDotNotation(varName);
            const utilityClass = utilities[varName] ? utilities[varName][0] : `.${varName}`;
            const value = resolveValue(data.value, variables);
            
            borderSizes.push({
                token: tokenName,
                css_variable: data.css_variable,
                utility_class: utilityClass,
                value: value,
            });
        } else if (varName.startsWith('token-border-style-')) {
            const tokenName = tokenToDotNotation(varName);
            const utilityClass = utilities[varName] ? utilities[varName][0] : `.${varName}`;
            
            borderStyles.push({
                token: tokenName,
                css_variable: data.css_variable,
                utility_class: utilityClass,
                value: data.value,
            });
        } else if (varName.startsWith('token-border-radius-')) {
            const tokenName = tokenToDotNotation(varName);
            const utilityClass = utilities[varName] ? utilities[varName][0] : `.${varName}`;
            const value = resolveValue(data.value, variables);
            
            borderRadii.push({
                token: tokenName,
                css_variable: data.css_variable,
                utility_class: utilityClass,
                value: value,
            });
        }
    });
    
    // Sort by token name
    const sortByToken = (a, b) => a.token.localeCompare(b.token);
    borderSizes.sort(sortByToken);
    borderStyles.sort(sortByToken);
    borderRadii.sort(sortByToken);
    
    const content = `export const Border = ${JSON.stringify(borderSizes, null, 4)};

export const BorderStyle = ${JSON.stringify(borderStyles, null, 4)};

export const BorderRadius = ${JSON.stringify(borderRadii, null, 4)};
`;
    
    writeModule('borders.ts', content);
    console.log('✓ Generated borders.ts');
}

/**
 * Look ahead a few lines from a class opening for the declaration that reveals
 * the spacing scale, e.g. margin-block-start: $token-space-100.
 */
function findScaleAhead(lines, start, valueRegex, maxAhead) {
    for (let j = start + 1; j < Math.min(start + maxAhead, lines.length); j++) {
        const valueMatch = lines[j].match(valueRegex);
        if (valueMatch) {
            return valueMatch[1];
        }
    }
    return null;
}

/**
 * Match a .token-margin-* / .token-padding-* class opening at lines[i] and
 * resolve its scale from the following declarations.
 */
function matchBoxSpacingClass(lines, i, property) {
    const classRegex = new RegExp(
        `^\\.token-(${property}(?:-top|-end|-bottom|-start|-vertical|-horizontal)?(?:-(\\d+|050|025|075))?)\\s*\\{`
    );
    const classMatch = lines[i].match(classRegex);
    if (!classMatch) {
        return null;
    }

    const valueRegex = new RegExp(`${property}-(?:block|inline)-(?:start|end):\\s*\\$token-space-(\\d+|050|025|075)`);
    const scale = findScaleAhead(lines, i, valueRegex, 10);
    return scale ? { className: `.token-${classMatch[1]}`, scale } : null;
}

/**
 * Match a .token-gap-* class opening at lines[i] and resolve its scale.
 */
function matchGapClass(lines, i) {
    const gapMatch = lines[i].match(/^\.token-gap-(\d+|050|025|075)\s*\{/);
    if (!gapMatch) {
        return null;
    }

    const scale = findScaleAhead(lines, i, /gap:\s*#\{\$token-space-(\d+|050|025|075)\}/, 5);
    return scale ? { className: `.token-gap-${gapMatch[1]}`, scale } : null;
}

/**
 * Parse margin, padding, and gap utilities from SCSS
 */
function parseSpacingUtilities(content) {
    const margins = [];
    const paddings = [];
    const gaps = [];

    // Match patterns like .token-margin-100 { ... margin-block-start: $token-space-100; }
    const lines = content.split('\n');

    for (let i = 0; i < lines.length; i++) {
        const margin = matchBoxSpacingClass(lines, i, 'margin');
        if (margin) {
            margins.push(margin);
        }

        const padding = matchBoxSpacingClass(lines, i, 'padding');
        if (padding) {
            paddings.push(padding);
        }

        const gap = matchGapClass(lines, i);
        if (gap) {
            gaps.push(gap);
        }

        // Match no-margin and no-padding
        if (lines[i].match(/^\.token-no-margin\s*\{/)) {
            margins.push({ className: '.token-no-margin', scale: '0' });
        }
        if (lines[i].match(/^\.token-no-padding\s*\{/)) {
            paddings.push({ className: '.token-no-padding', scale: '0' });
        }
    }

    return { margins, paddings, gaps };
}

const SPACING_DIRECTION_SUFFIXES = [
    { infix: '' },
    { infix: '-top' },
    { infix: '-end' },
    { infix: '-bottom' },
    { infix: '-start' },
];

/**
 * Infer margin/padding/gap utility classes from the spacing scale when _utilities.scss
 * is absent (OUI build:tokens uses --utilities false). Names match outsystems-design-tokens.
 */
function inferSpacingUtilities(spacing) {
    const margins = [];
    const paddings = [];
    const gaps = [];

    spacing.forEach((row) => {
        const scaleMatch = row.token.match(/^space\.(\d+|050|025|075)$/);
        if (!scaleMatch) return;

        const scale = scaleMatch[1];
        SPACING_DIRECTION_SUFFIXES.forEach(({ infix }) => {
            margins.push({ className: `.token-margin${infix}-${scale}`, scale });
            paddings.push({ className: `.token-padding${infix}-${scale}`, scale });
        });
        gaps.push({ className: `.token-gap-${scale}`, scale });
    });

    SPACING_DIRECTION_SUFFIXES.forEach(({ infix }) => {
        margins.push({
            className: infix ? `.token-margin${infix}` : '.token-margin',
            scale: '400',
        });
        paddings.push({
            className: infix ? `.token-padding${infix}` : '.token-padding',
            scale: '400',
        });
    });

    margins.push({ className: '.token-margin-vertical', scale: '400' });
    margins.push({ className: '.token-margin-horizontal', scale: '400' });
    paddings.push({ className: '.token-padding-vertical', scale: '400' });
    paddings.push({ className: '.token-padding-horizontal', scale: '400' });
    margins.push({ className: '.token-no-margin', scale: '0' });
    paddings.push({ className: '.token-no-padding', scale: '0' });

    return { margins, paddings, gaps };
}

/**
 * Generate spacing.js
 */
function generateSpacing(variables, utilities, utilitiesContent) {
    const spacing = [];
    
    Object.entries(variables).forEach(([varName, data]) => {
        if (varName.startsWith('token-space-')) {
            const tokenName = tokenToDotNotation(varName);
            const utilityClass = utilities[varName] ? utilities[varName][0] : `.${varName}`;
            const value = resolveValue(data.value, variables);
            
            spacing.push({
                token: tokenName,
                css_variable: data.css_variable,
                utility_class: utilityClass,
                value: value,
            });
        }
    });
    
    // Sort by numeric value
    spacing.sort((a, b) => {
        const aVal = parseFloat(a.value);
        const bVal = parseFloat(b.value);
        return aVal - bVal;
    });
    
    // Parse margin/padding/gap utilities from SCSS when available; otherwise infer by convention
    let { margins: marginUtils, paddings: paddingUtils, gaps: gapUtils } =
        parseSpacingUtilities(utilitiesContent);

    if (marginUtils.length === 0 && paddingUtils.length === 0 && gapUtils.length === 0) {
        ({ margins: marginUtils, paddings: paddingUtils, gaps: gapUtils } = inferSpacingUtilities(spacing));
    }
    
    // Build margin array from parsed utilities
    const margins = [];
    marginUtils.forEach(({ className, scale }) => {
        const spaceVar = `token-space-${scale}`;
        const value = variables[spaceVar] ? resolveValue(variables[spaceVar].value, variables) : `${scale}px`;
        
        // Determine usage text
        let usage = '';
        if (className.includes('-top')) {
            usage = `Apply ${value} margin to top`;
        } else if (className.includes('-end')) {
            usage = `Apply ${value} margin to end`;
        } else if (className.includes('-bottom')) {
            usage = `Apply ${value} margin to bottom`;
        } else if (className.includes('-start')) {
            usage = `Apply ${value} margin to start`;
        } else if (className.includes('-vertical')) {
            usage = `Apply ${value} margin to top and bottom`;
        } else if (className.includes('-horizontal')) {
            usage = `Apply ${value} margin to start and end`;
        } else {
            usage = `Apply ${value} margin to all sides`;
        }
        
        margins.push({
            utility_class: className,
            value: value,
            usage: usage
        });
    });
    
    // Build padding array from parsed utilities
    const paddings = [];
    paddingUtils.forEach(({ className, scale }) => {
        const spaceVar = `token-space-${scale}`;
        const value = variables[spaceVar] ? resolveValue(variables[spaceVar].value, variables) : `${scale}px`;
        
        // Determine usage text
        let usage = '';
        if (className.includes('-top')) {
            usage = `Apply ${value} padding to top`;
        } else if (className.includes('-end')) {
            usage = `Apply ${value} padding to end`;
        } else if (className.includes('-bottom')) {
            usage = `Apply ${value} padding to bottom`;
        } else if (className.includes('-start')) {
            usage = `Apply ${value} padding to start`;
        } else if (className.includes('-vertical')) {
            usage = `Apply ${value} padding to top and bottom`;
        } else if (className.includes('-horizontal')) {
            usage = `Apply ${value} padding to start and end`;
        } else {
            usage = `Apply ${value} padding to all sides`;
        }
        
        paddings.push({
            utility_class: className,
            value: value,
            usage: usage
        });
    });
    
    // Build gap array from parsed utilities
    const gaps = [];
    gapUtils.forEach(({ className, scale }) => {
        const spaceVar = `token-space-${scale}`;
        const value = variables[spaceVar] ? resolveValue(variables[spaceVar].value, variables) : `${scale}px`;
        
        gaps.push({
            utility_class: className,
            value: value,
            usage: `Sets gap spacing to ${value}`
        });
    });
    
    const content = `export const Spacing = ${JSON.stringify(spacing, null, 4)};

export const Margin = ${JSON.stringify(margins, null, 4)};

export const Padding = ${JSON.stringify(paddings, null, 4)};

export const Gap = ${JSON.stringify(gaps, null, 4)};
`;
    
    writeModule('spacing.ts', content);
    console.log('✓ Generated spacing.ts');
}

/**
 * Usage blurb for a token-bg-{category}-{variant} background token.
 */
function bgUsage(category, variant) {
    if (variant.includes('base-default')) return `Default ${category} background`;
    if (variant.includes('base-press')) return `Pressed state ${category} background`;
    if (variant.includes('subtle-default')) return `Subtle ${category} background`;
    if (variant.includes('subtle-press')) return `Pressed state subtle ${category} background`;
    return '';
}

/** Capitalize the first letter (primary -> Primary). */
function capitalize(value) {
    return value.charAt(0).toUpperCase() + value.slice(1);
}

/** Flat color roles collected by prefix into a top-level colors.* array. */
const COLOR_ROLE_GROUPS = [
    { key: 'text', prefix: 'token-text-' },
    { key: 'surface', prefix: 'token-surface-' },
    { key: 'border', prefix: 'token-border-', exclude: /-(size|radius|style)-/ },
    { key: 'icon', prefix: 'token-icon-' },
];

/**
 * Generate colors.js
 */
function generateColors(variables, utilities) {
    const colors = {
        semanticsbase: [],
        semantics: {
            primary: [],
            info: [],
            success: [],
            danger: [],
            warning: [],
        },
        primitives: {
            neutral: [],
            red: [],
            pumpkin: [],
            orange: [],
            yellow: [],
            lime: [],
            green: [],
            teal: [],
            aqua: [],
            blue: [],
            indigo: [],
            violet: [],
            purple: [],
            magenta: [],
            pink: [],
            base: [],
        },
        bg: {
            primary: [],
            danger: [],
            success: [],
            info: [],
            warning: [],
        },
        text: [],
        surface: [],
        border: [],
        icon: [],
    };
    
    // Shared trailing fields of every color entry (values are always lowercased)
    const entryFields = (varName, data) => ({
        token: tokenToDotNotation(varName),
        css_variable: data.css_variable,
        utility_class: utilities[varName] ? utilities[varName][0] : `.${varName}`,
        value: resolveValue(data.value, variables).toLowerCase(),
    });

    const namedEntry = (name, varName, data) => ({
        name,
        usage: ' ',
        ...entryFields(varName, data),
    });

    // Background colors (bg-primary-*, bg-danger-*, etc.)
    const collectBackground = (varName, data) => {
        const match = varName.match(/^token-bg-(primary|danger|success|info|warning)-(.+)$/);
        if (!match) return false;
        colors.bg[match[1]].push({
            ...entryFields(varName, data),
            usage: bgUsage(match[1], match[2]),
        });
        return true;
    };

    // Semantics base colors
    const collectSemanticsBase = (varName, data) => {
        const match = varName.match(/^token-semantics-(primary|info|success|danger|warning)-base$/);
        if (!match) return false;
        colors.semanticsbase.push(namedEntry(capitalize(match[1]), varName, data));
        return true;
    };

    // Semantics color scales
    const collectSemanticsScale = (varName, data) => {
        const match = varName.match(/^token-semantics-(primary|info|success|danger|warning)-(\d+)$/);
        if (!match || !colors.semantics[match[1]]) return false;
        colors.semantics[match[1]].push(namedEntry(`${capitalize(match[1])} ${match[2]}`, varName, data));
        return true;
    };

    // Primitives
    const collectPrimitiveScale = (varName, data) => {
        const match = varName.match(
            /^token-primitives-(neutral|red|pumpkin|orange|yellow|lime|green|teal|aqua|blue|indigo|violet|purple|magenta|pink)-(\d+)$/
        );
        if (!match || !colors.primitives[match[1]]) return false;
        colors.primitives[match[1]].push(namedEntry(`${capitalize(match[1])} ${match[2]}`, varName, data));
        return true;
    };

    // Base colors (white, black)
    const collectPrimitiveBase = (varName, data) => {
        const match = varName.match(/^token-primitives-base-(white|black)$/);
        if (!match) return false;
        colors.primitives.base.push(namedEntry(capitalize(match[1]), varName, data));
        return true;
    };

    // Text / surface / border / icon colors
    const collectRole = (varName, data) => {
        for (const { key, prefix, exclude } of COLOR_ROLE_GROUPS) {
            if (!varName.startsWith(prefix) || (exclude && exclude.test(varName))) continue;
            colors[key].push(namedEntry(varName.replace(prefix, '').replace(/-/g, ' '), varName, data));
            return true;
        }
        return false;
    };

    Object.entries(variables).forEach(([varName, data]) => {
        if (varName.includes('-rgb')) return; // rgb triplet variants are never documented
        if (collectBackground(varName, data)) return;
        if (collectSemanticsBase(varName, data)) return;
        if (collectSemanticsScale(varName, data)) return;
        if (collectPrimitiveScale(varName, data)) return;
        if (collectPrimitiveBase(varName, data)) return;
        collectRole(varName, data);
    });
    
    const content = `export const Colors = ${JSON.stringify(colors, null, 4)};
`;
    
    writeModule('colors.ts', content);
    console.log('✓ Generated colors.ts');
}

/**
 * Generate elevation.js
 */
function generateElevation(variables, utilities) {
    const elevations = [];
    const zIndices = [];
    
    Object.entries(variables).forEach(([varName, data]) => {
        if (varName.match(/^token-elevation-\d+$/)) {
            const level = varName.match(/elevation-(\d+)/)[1];
            const usageText = {
                '1': 'Used for foundational components like cards to create a subtle lift from the background.',
                '2': 'Ideal for interactive elements such as top bar, tooltips, and layered components that appear on hover or click.',
                '3': 'Reserved for components that provide feedback like bottom sheet or toasts, or secondary navigational elements.',
                '4': 'The highest elevation, designed for high-priority and interruptive elements such as modals and side menus that appear over all other content.',
            };
            
            elevations.push({
                token: tokenToDotNotation(varName),
                css_variable: data.css_variable,
                utility_class: utilities[varName] ? utilities[varName][0] : `.${varName}`,
                value: resolveShadowValue(data.value, variables),
                usage: usageText[level] || '',
            });
        } else if (varName.startsWith('token-z-index-')) {
            const level = varName.replace('token-z-index-', '');
            const usageText = {
                '0': 'Base level z-index for elements that should be at the default stacking level.',
                '100': 'Low priority layering for subtle UI elements.',
                '200': 'Standard layering for components like dropdowns and popovers.',
                '300': 'Medium priority layering for components like fixed headers or sticky elements.',
                '400': 'High priority layering for important overlays like bottom sheets or side menus.',
                '500': 'Highest standard priority layering for critical modals and dialogs.',
                'bottom': 'Forces an element to appear below all other content on the page.',
                'top': 'Forces an element to appear above all other content on the page.',
            };
            
            zIndices.push({
                token: tokenToDotNotation(varName),
                css_variable: data.css_variable,
                utility_class: utilities[varName] ? utilities[varName][0] : `.${varName}`,
                value: data.value,
                usage: usageText[level] || '',
            });
        }
    });
    
    // Sort elevations
    elevations.sort((a, b) => parseInt(a.token.split('.')[1]) - parseInt(b.token.split('.')[1]));
    
    const content = `export const Elevation = ${JSON.stringify(elevations, null, 4)};

export const ZIndex = ${JSON.stringify(zIndices, null, 4)};
`;
    
    writeModule('elevation.ts', content);
    console.log('✓ Generated elevation.ts');
}

