/* ── Small building blocks ─────────────────────────────────────────────── */

function Swatch({ color }: { color: string | null }) {
	if (!isColor(color)) return null;
	return <span className="mg-swatch" style={{ background: color as string }} title={color as string} />;
}

function Value({ v }: { v: string | null }) {
	if (!v) return <span className="mg-dim">—</span>;
	if (v.startsWith('color-mix')) return <span className="mg-dim">primary at 22% (color-mix)</span>;
	return (
		<span className="mg-value">
			<Swatch color={v} />
			<code>{v}</code>
		</span>
	);
}

function Stat({ n, label, tone }: { n: number; label: string; tone: 'stop' | 'warn' | 'ok' | 'new' }) {
	return (
		<div className={`mg-stat mg-stat--${tone}`}>
			<div className="mg-stat-n">{n}</div>
			<div className="mg-stat-label">{label}</div>
		</div>
	);
}

type Tone = 'stop' | 'warn' | 'ok' | 'tip';

function Pill({ tone, children }: { tone: Tone; children: React.ReactNode }) {
	return <span className={`mg-pill mg-pill--${tone}`}>{children}</span>;
}

